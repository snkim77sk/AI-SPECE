def _option(name, label, kind, source_url, website_url):
    # Fresh dictionaries prevent callers from modifying the shared snapshot.
    return {
        "name": name,
        "label": label,
        "kind": kind,
        "source_url": source_url,
        "website_url": website_url,
        "official": True,
    }


def official_institutions(region):
    """Return verified current institutions for one recognized parent region.

    Blank, unknown and historical predecessor regions have no current defaults.
    One-to-one renamed regions are handled by the shared geography normalizer.
    Bare municipality names remain compatible with existing query parameters;
    labels include the parent region so equal names cannot imply equal identity.
    """
    selected = canonical_region(region)
    directory = _LOCAL_GOVERNMENT_DIRECTORY.get(selected)
    if directory is None:
        return []
    website, children = directory
    options = [_option(
        selected, selected + " \ubcf8\uccad", "PROVINCE", MOIS_SOURCE_URL, website
    )]
    options.extend(
        _option(name, selected + " " + name, kind, MOIS_SOURCE_URL, child_website)
        for name, kind, child_website in children
    )
    office, office_website = _EDUCATION_OFFICES[selected]
    options.append(_option(office, office, "EDUCATION_OFFICE", MOE_SOURCE_URL, office_website))
    return options
